// F8 AI features: AI-01..08 (plan .plans/e2e-scenarios.md, "F8 AI features").
//
// Every model call goes to the provider stub's OpenAI-compatible endpoint
// (OPENAI_BASE_URL = <stub>/openai/v1, GEMINI_API_KEY blank; lib/ai.ts
// createClient). The stub picks a fixture by keyword in the last user message
// (support/provider-stub/server.mjs pickFixtureName) or by a forced rule.
//
// Verified against the code:
// - /app/ai-invoice (AIInvoicePrompt + AIInvoicePreview): textarea under
//   "Instruksi AI", submit "Generate draft" -> POST /api/invoices/ai. 200 ->
//   AIInvoicePreview renders InvoiceFormClient ("Review draft invoice") prefilled
//   with the draft; any non-OK -> role=alert with body.error ("Invalid AI
//   response") and the empty fallback form. The route parses the first {...}
//   of the completion with AIInvoiceSchema; a parse failure or a provider
//   error is a 400 { error: "Invalid AI response", fallback }.
// - /app/insight (server page builds the summary, InsightClient POSTs it to
//   /api/ai/invoice-insight on mount). The route answers 200 { data, fallback }
//   either way; fallback true renders "Insight menampilkan data fallback ...".
//   The prompt contains "analis finansial" (insight fixture) and the summary
//   JSON (client names).
// - /app/settings/theme (ThemeSettingsPanel): "Dapatkan Saran AI" -> POST
//   /api/ai/theme-suggest { brandName, preferredMode } -> applyAiTheme (not
//   persisted) and shows the label/description; the hex labels next to the
//   colour inputs show the applied palette. Prompt contains "palet warna".
// - /app/receipts/scan (ReceiptScanner): a hidden <input type=file
//   accept=image/*>; the file is read as a data URL and POSTed to
//   /api/receipts/ai-scan as { image }; the route sends it as an image_url part
//   (stub -> receipt-scan fixture). Success shows "Data berhasil diekstrak!" and
//   the prefilled "Review draft invoice" form.
// - AI-06: the OpenAI SDK (openai 4.x) retries 503 twice (maxRetries 2), so
//   the stub is forced to 503 for 3 calls; the spec asserts on the first
//   request and tolerates 1..3 recorded calls.
// - AI-07: POST /api/ai/explain is platform-admin only (401/403 covered by
//   SEC-12) and takes { recommendation_id } of an existing OptimizationLog.
//   No app route creates OptimizationLog rows, so the DB seed
//   (support/db/seed-platform-admin.mjs) adds one APPLIED row with the fixed id
//   below. GET /api/ai-optimizer/recommendations is public and lists PENDING
//   rows as { route, confidence } only; it reads the DB, never PostHog
//   (POSTHOG_API_KEY is blank, so the stub's /posthog host sees no call).
// - AI-08: GET /api/ai/orchestrator and /devtools/ai-agents are platform-admin
//   only; ENABLE_AI_ORCHESTRATION=memory keeps the stream in process.
