/** Text of the last user message the app sent to the stub (string or multi-part content). */
function lastUserContent(request: StubRequest): { text: string; parts: Array<{ type?: string; image_url?: { url?: string } }> } {
  const body = request.json as { messages?: Array<{ role: string; content: unknown }> } | undefined;
  const user = [...(body?.messages ?? [])].reverse().find((message) => message.role === "user");
  if (typeof user?.content === "string") return { text: user.content, parts: [] };
  const parts = Array.isArray(user?.content) ? (user.content as Array<{ type?: string; text?: string; image_url?: { url?: string } }>) : [];
  return { text: parts.filter((part) => part.type === "text").map((part) => part.text ?? "").join("\n"), parts };
}

const aiPrompt = (page: Page) => page.getByRole("textbox").first();
const generateButton = (page: Page) => page.getByRole("button", { name: "Generate draft" });
const reviewHeading = (page: Page) => page.getByRole("heading", { name: "Review draft invoice" });

async function listInvoiceIds(api: { get(url: string): Promise<import("@playwright/test").APIResponse> }): Promise<string[]> {
  const response = await api.get("/api/invoices");
  expect(response.status()).toBe(200);
  const body = (await response.json()) as { data: InvoiceRecord[] };
  return body.data.map((invoice) => invoice.id);
}

test.describe("AI invoice composer (/app/ai-invoice)", () => {
  test.slow();

  test(
    "AI-01 a prompt is sent to the model, the draft prefills the form, and saving creates the invoice",
    { annotation: covers("/app/ai-invoice", "/api/invoices/ai", "/api/invoices") },
    async ({ isolatedUser, stub }) => {
      const { page } = isolatedUser;
      const prompt = `AI-01 ${tag()}: buat invoice desain website 2x dan hosting tahunan untuk Acme`;

      await page.goto("/app/ai-invoice");
      await expect(page.getByRole("heading", { name: "Buat draft invoice dari perintah natural language" })).toBeVisible();
      await aiPrompt(page).fill(prompt);
      const generated = page.waitForResponse(
        (r) => new URL(r.url()).pathname === "/api/invoices/ai" && r.request().method() === "POST",
      );
      await generateButton(page).click();
      expect((await generated).status()).toBe(200);

      const calls = await stub.requests(COMPLETIONS);
      expect(calls).toHaveLength(1);
      expect(calls[0].method).toBe("POST");
      expect(lastUserContent(calls[0]).text).toBe(prompt);

      await expect(reviewHeading(page)).toBeVisible();
      const form = new InvoiceFormPage(page);
      await expect(form.client).toHaveValue(DRAFT.client);
      await expect(form.notes).toHaveValue(DRAFT.notes);
      for (const [index, item] of DRAFT.items.entries()) {
        await expect(form.itemName(index)).toHaveValue(item.name);
        await expect(form.itemQty(index)).toHaveValue(String(item.qty));
        await expect(form.itemPrice(index)).toHaveValue(String(item.price));
      }

      const created = page.waitForResponse(
        (r) => new URL(r.url()).pathname === "/api/invoices" && r.request().method() === "POST",
      );
      await form.saveDraft();
      const response = await created;
      expect(response.status()).toBe(201);
      const { data: invoice } = (await response.json()) as { data: InvoiceRecord };
      const subtotal = DRAFT.items.reduce((sum, item) => sum + item.qty * item.price, 0);
      expect(invoice).toMatchObject({ client: DRAFT.client, status: "DRAFT", subtotal, notes: DRAFT.notes });
      expect(invoice.items).toHaveLength(DRAFT.items.length);
      await expect(page).toHaveURL(new RegExp(`/app/invoices/${invoice.id}$`));
      expect(await listInvoiceIds(isolatedUser.api)).toContain(invoice.id);
    },
  );

  test(
    "AI-02 a malformed completion shows a visible error and creates no invoice",
    { annotation: covers("/app/ai-invoice", "/api/invoices/ai") },
    async ({ isolatedUser, stub }) => {
      const { page, api } = isolatedUser;
      const before = await listInvoiceIds(api);

      await page.goto("/app/ai-invoice");
      // "malformed" in the prompt selects the completion-malformed fixture.
      await aiPrompt(page).fill(`AI-02 ${tag()} malformed draft please`);
      const generated = page.waitForResponse(
        (r) => new URL(r.url()).pathname === "/api/invoices/ai" && r.request().method() === "POST",
      );
      await generateButton(page).click();
      const response = await generated;
      expect(response.status()).toBe(400);
      expect(await response.json()).toMatchObject({ error: "Invalid AI response", fallback: { client: "" } });

      await expect(page.getByRole("alert").filter({ hasText: "Invalid AI response" })).toBeVisible();
      expect(await stub.requests(COMPLETIONS)).toHaveLength(1);
      // The empty fallback form is shown for manual entry; nothing was saved.
      await expect(new InvoiceFormPage(page).client).toHaveValue("");
      expect(await listInvoiceIds(api)).toEqual(before);
    },
  );

  test(
    "AI-06 the model answering 503 surfaces an error in the UI within 20 s (no hang)",
    { annotation: covers("/app/ai-invoice", "/api/invoices/ai") },
    async ({ isolatedUser, stub }) => {
      const { page, api } = isolatedUser;
      const before = await listInvoiceIds(api);
      // 1 call + the OpenAI SDK's 2 default retries.
      await stub.force({ target: COMPLETIONS, status: 503, count: 3 });

      await page.goto("/app/ai-invoice");
      await aiPrompt(page).fill(`AI-06 ${tag()}: invoice konsultasi 1 juta`);
      const started = Date.now();
      await generateButton(page).click();
      await expect(page.getByRole("alert").filter({ hasText: "Invalid AI response" })).toBeVisible({ timeout: 20_000 });
      const elapsed = Date.now() - started;
      expect(elapsed, `UI error after ${elapsed} ms`).toBeLessThan(20_000);
      await expect(generateButton(page)).toBeEnabled();

      const calls = await stub.requests(COMPLETIONS);
      expect(calls.length).toBeGreaterThanOrEqual(1);
      expect(calls.length).toBeLessThanOrEqual(3);
      expect(calls[0].method).toBe("POST");
      expect(lastUserContent(calls[0]).text).toContain("AI-06");
      expect(await listInvoiceIds(api)).toEqual(before);
    },
  );
});

