test.describe("AI governance and orchestration (platform admin)", () => {
  test(
    "AI-07 POST /api/ai/explain returns the canned explanation; GET /api/ai-optimizer/recommendations lists { route, confidence } only",
    { annotation: covers("/api/ai/explain", "/api/ai-optimizer/recommendations") },
    async ({ persona, api, stub }) => {
      const admin = await persona("platformAdmin");

      const explained = await admin.api.post("/api/ai/explain", { data: { recommendation_id: E2E_AI_RECOMMENDATION_ID } });
      expect(explained.status()).toBe(200);
      const { data } = (await explained.json()) as { data: Record<string, unknown> };
      expect(data).toMatchObject({
        recommendationId: E2E_AI_RECOMMENDATION_ID,
        route: "/app/insight",
        ...EXPLAIN,
      });
      expect(typeof data.id).toBe("string");
      expect(typeof data.trustScore).toBe("number");

      const calls = await stub.requests(COMPLETIONS);
      expect(calls).toHaveLength(1);
      const sent = lastUserContent(calls[0]).text;
      expect(sent).toContain("AI governance explainer");
      expect(sent).toContain('"route": "/app/insight"');

      // An unknown recommendation id is a 400 and never reaches the model.
      await stub.reset();
      const unknown = await admin.api.post("/api/ai/explain", { data: { recommendation_id: `missing-${tag()}` } });
      expect(unknown.status()).toBe(400);
      expect(await stub.requests(COMPLETIONS)).toHaveLength(0);

      // Public list: PENDING OptimizationLog rows reduced to { route, confidence }.
      const listed = await api.get("/api/ai-optimizer/recommendations");
      expect(listed.status()).toBe(200);
      const body = (await listed.json()) as { recommendations: Array<Record<string, unknown>> };
      expect(Object.keys(body)).toEqual(["recommendations"]);
      expect(Array.isArray(body.recommendations)).toBe(true);
      for (const entry of body.recommendations) {
        expect(Object.keys(entry).sort()).toEqual(["confidence", "route"]);
        expect(typeof entry.route).toBe("string");
        expect(typeof entry.confidence).toBe("number");
      }
      // The seeded row is APPLIED, so it is not offered for prefetching.
      expect(body.recommendations.map((entry) => entry.route)).not.toContain("/app/insight");
      // The list reads the DB only; no PostHog query reaches the stubbed host.
      expect(await stub.requests("/posthog")).toHaveLength(0);
    },
  );

  test(
    "AI-08 GET /api/ai/orchestrator returns the snapshot and /devtools/ai-agents renders it",
    { annotation: covers("/api/ai/orchestrator", "/devtools/ai-agents") },
    async ({ persona }) => {
      const admin = await persona("platformAdmin");

      const snapshotResponse = await admin.api.get("/api/ai/orchestrator");
      expect(snapshotResponse.status()).toBe(200);
      expect(snapshotResponse.headers()["cache-control"]).toBe("no-store");
      const snapshot = (await snapshotResponse.json()) as {
        enabled: boolean;
        agents: Array<{ agentId: string; name: string; priority: number }>;
        events: Array<{ traceId: string; type: string; source: string }>;
        conflicts: unknown[];
        lastUpdated: string;
      };
      expect(snapshot.enabled).toBe(true);
      expect(Array.isArray(snapshot.agents)).toBe(true);
      expect(Array.isArray(snapshot.events)).toBe(true);
      expect(Array.isArray(snapshot.conflicts)).toBe(true);
      expect(Number.isNaN(Date.parse(snapshot.lastUpdated))).toBe(false);

      const { page } = admin;
      await page.goto("/devtools/ai-agents");
      await expect(page).toHaveURL(/\/devtools\/ai-agents$/);
      await expect(page.getByRole("heading", { name: "AI Agent Orchestration", level: 1 })).toBeVisible();
      await expect(page.getByRole("heading", { name: "Multi-agent orchestration" })).toBeVisible();
      await expect(page.getByText("Visualisasi hubungan antar agen dan aktivitas event stream AI.")).toBeVisible();
      await expect(page.getByRole("heading", { name: /^Log terbaru \(\d+\)$/ })).toBeVisible();
      await expect(page.getByRole("heading", { name: "Trace audit" })).toBeVisible();
      // The page reads the same in-process registry and stream as the API.
      for (const agent of snapshot.agents) {
        await expect(page.getByText(agent.name, { exact: true }).first()).toBeVisible();
      }
      if (snapshot.events.length === 0) {
        await expect(page.getByText("Belum ada event yang terekam untuk filter saat ini.")).toBeVisible();
      }
    },
  );
});
